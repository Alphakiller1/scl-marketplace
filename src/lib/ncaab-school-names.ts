export function ncaabSchoolName(teamName: string): string {
  const trimmed = teamName.trim();
  const withoutRank = trimmed.replace(/^(?:#\d+\s+|\d+\.\s+)/, "");
  // Unknown teams retain their whole name; never guess a school from a mascot.
  return schoolByTeam.get(canonicalNcaabTeamName(withoutRank)) ?? trimmed;
}
